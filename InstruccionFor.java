public class InstruccionFor {
    public static void main(String[] args) {
        // Un bucle for para imprimir "Texto " seguido del número actual, del 1 al 10.
        for(int numero = 1; numero <= 10; numero = numero + 1) {
            // Se han corregido las comillas tipográficas por comillas rectas ("").
            System.out.println("Texto " + numero);
        }
    } // Fin del método main
} // Fin de la clase InstruccionFor